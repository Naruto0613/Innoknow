export const getVocabularyWords = (): VocabularyWord[] => {
  const merged: Omit<VocabularyWord, "id">[] = [];
  const addedWords = new Set<string>();

  rawVocabulary.forEach((item) => {
    const key = item.word.toLowerCase().trim();
    if (!addedWords.has(key)) {
      addedWords.add(key);
      merged.push(item);
    }
  });

  supplementaryPremiumWords.forEach((item) => {
    const key = item.word.toLowerCase().trim();
    if (!addedWords.has(key)) {
      addedWords.add(key);
      merged.push(item);
    }
  });

  return merged.map((item, idx) => ({
    id: String(idx + 1),
    word: item.word.trim(),
    translation: item.translation.trim(),
    pos: item.pos,
    level: item.level,
    category: item.category,
    example: item.example.trim(),
    exampleMn: item.exampleMn.trim(),
  }));
};
